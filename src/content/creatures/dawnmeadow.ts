import type { CreatureDef, DropDef } from './types';

/**
 * Dawnmeadow's tier 1 roster (POW-M4-05, regions/01-dawnmeadow section 3): 16 new creatures and a
 * tier 2 visitor. Stats here are the step "a" values. Spawn zones multiply them for steps b and c
 * (balance/world.ts). The Mossling is the par: 125 Health, a time to kill of 4 to 8 seconds.
 *
 * Every attack names its telegraph in `content/combat/attacks`; the validator holds each to the
 * tier minimum. Temperament decides who starts a fight (design/04, D20).
 */

const drop = (item: string, chance: number, min = 1, max = min): DropDef => ({
  item,
  chance,
  min,
  max,
});
const coin = (chance: number, min: number, max = min): DropDef =>
  drop('item.coin', chance, min, max);

/** What every entry shares unless it says otherwise. */
const base = {
  tier: 1,
  wander: true,
  staggerMax: 30,
} as const;

function make(
  c: Omit<CreatureDef, 'tier' | 'wander' | 'staggerMax' | 'sounds' | 'sprite'> & {
    tier?: number;
    wander?: boolean;
    staggerMax?: number;
    voice: string;
    sprite?: string;
  },
): CreatureDef {
  const { voice, sprite, ...rest } = c;
  return {
    ...base,
    ...rest,
    sprite: sprite ?? c.id,
    sounds: { notice: `sfx.${voice}_notice`, die: `sfx.${voice}_die` },
  } as CreatureDef;
}

