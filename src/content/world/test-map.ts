/*
 * The 3 x 3 chunk test map (96 x 96 tiles), authored as an ASCII stamp.
 *
 * STAMP FORMAT v0 (extended in M4): `legend` maps one character to a cell: the ground terrain
 * plus optional detail, object and overhead tiles. `rows` is the grid, top left is world tile
 * (0, 0), all rows the same width, size a multiple of 32. Objects (spawn points) list world tiles.
 *
 * Legend:  . grass   d dirt   ~ water   , ; : v flowers (white, rose, ochre, violet)
 *          T U oak   P Q pine   A autumn   I birch   L blossom   X dead tree   (object + canopy)
 *          B bush   b berry bush   y dry bush   R rock
 *
 * The map was laid out with lakes, a river, roads and one biome per chunk so every blob autotile
 * case (edges, outside corners, inside corners, peninsulas) shows somewhere.
 */

const tree = (trunk: string, canopy: string): StampCell => ({
  ground: Terrain.Grass,
  object: tilesetId(trunk),
  overhead: tilesetId(canopy),
});
const bush = (id: string): StampCell => ({ ground: Terrain.Grass, object: tilesetId(id) });
const flower = (id: string): StampCell => ({ ground: Terrain.Grass, detail: tilesetId(id) });

