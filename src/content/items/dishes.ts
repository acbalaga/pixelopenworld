/**
 * The dishes of POW-M6-04 (design/05 Cooking, design/13 section 2): 85 new recipes on top of the
 * 15 the slice had, for 100 cooking recipes in tiers 1 to 4. Each row makes the dish item and its
 * recipe. What a dish restores comes from its tier and kind (`COOKING.byTier`), so a row holds
 * only what is particular to it: where it is cooked, what goes in, how it is learned.
 *
 * Learning: `experiment` dishes are found by trying ingredients; `teach` dishes are taught by the
 * person named; `buy` and `find` dishes are in a cookbook (bought in a shop or found in a chest),
 * which teaches every recipe that names it. The ten dishes of animal goods (egg, duck egg, milk,
 * goat milk, truffle) wait for Husbandry (POW-M6-03): their ingredients have no source yet.
 */

/** What a dish is for: Health, Stamina, Focus, or all three (a feast). */
export type DishKind = 'hp' | 'sta' | 'foc' | 'all';

export interface DishDef {
  /** `item.<key>` and `recipe.<key>`. */
  key: string;
  tier: 1 | 2 | 3 | 4;
  station: 'pot' | 'oven';
  ingredients: readonly (readonly [item: string, qty?: number])[];
  learn: Exclude<RecipeLearn, 'start'>;
  /** `teach`: the person. `buy` and `find`: the cookbook item. */
  from?: string;
  kind: DishKind;
  name: string;
  desc: string;
  /** Can be sold from a market stall (POW-M6-11). Dishes are, unless they spoil. */
  stall?: false;
}

