export const DISHES: readonly DishDef[] = ROWS.map(
  ([key, tier, station, ingredients, how, kind, name, desc]) => {
    const [learn, from] = how.split(':') as [DishDef['learn'], string | undefined];
    return {
      key,
      tier,
      station,
      ingredients,
      learn,
      ...(from ? { from: how.slice(learn.length + 1) } : {}),
      kind,
      name,
      desc,
    };
  },
);

/** A dish's restore and Fed buff, from its tier and kind. */
function foodOf(d: DishDef): NonNullable<ItemDef['food']> {
  const b = C.byTier[d.tier]!;
  const side = (n: number): number => Math.round((n * C.sidePct) / 100);
  const feast = (n: number): number => Math.round((n * C.feastPct) / 100);
  const main = (k: DishKind): boolean => d.kind === k;
  const all = d.kind === 'all';
  const hp = all ? feast(b.main) : main('hp') ? b.main : side(b.main);
  const sta = all ? feast(b.pool) : main('sta') ? b.pool : side(b.pool);
  const foc = all ? feast(b.pool) : main('foc') ? b.pool : side(b.pool);
  return {
    hp,
    sta,
    foc,
    fed: {
      ticks: b.fedMin * C.ticksPerMinute,
      hpMax: all || main('hp') ? b.max : 0,
      staMax: all || main('sta') ? b.max * 10 : 0,
      focMax: all || main('foc') ? b.max * 10 : 0,
    },
  };
}

