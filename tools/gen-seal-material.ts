// Generates the seal material for one `sealVersion` (tech/02, POW-M2-03): four random fragments,
// each in its own module under src/save/seal/v<N>/, and the registry that lists every version.
// Run once per version and commit the output:
//
//   npx tsx tools/gen-seal-material.ts --version 1
//
// Old versions are never rewritten or removed, so files sealed under them keep opening.
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Fragments per version, and bytes per fragment. */
export const FRAGMENT_COUNT = 4;
export const FRAGMENT_BYTES = 24;

/** Fresh random fragments. `random` is injectable for tests. */
export function makeFragments(
  random: (n: number) => Uint8Array = (n) => randomBytes(n),
): Uint8Array[] {
  return Array.from({ length: FRAGMENT_COUNT }, () => Uint8Array.from(random(FRAGMENT_BYTES)));
}

/** The module text for one fragment. */
export function fragmentModule(index: number, bytes: Uint8Array): string {
  return `// Generated by tools/gen-seal-material.ts. Do not edit. Committed on purpose: see docs/tech/02.
export const f${index} = new Uint8Array([${[...bytes].join(', ')}]);
`;
}

/** The module that gathers one version's fragments. */
export function versionIndex(): string {
  const names = Array.from({ length: FRAGMENT_COUNT }, (_, i) => `f${i}`);
  return `// Generated by tools/gen-seal-material.ts. Do not edit.
${names.map((n) => `import { ${n} } from './${n}';`).join('\n')}

export const FRAGMENTS: readonly Uint8Array[] = [${names.join(', ')}];
`;
}

/** The registry of every version found under `dir`. */
export function registryModule(versions: number[]): string {
  const sorted = [...versions].sort((a, b) => a - b);
  return `// Generated by tools/gen-seal-material.ts. Do not edit.
// Every sealVersion ever issued stays here, so old backups always open.

/** Versions that exist, oldest first. */
export const SEAL_VERSIONS: readonly number[] = [${sorted.join(', ')}];

/** The version new exports are sealed with. */
export const CURRENT_SEAL_VERSION = ${sorted[sorted.length - 1]};

/** Loads the fragments of one version. A dynamic import, so a build that injects its own material leaves these modules out. */
export async function loadCommitted(version: number): Promise<readonly Uint8Array[] | null> {
  switch (version) {
${sorted.map((v) => `    case ${v}:\n      return (await import('./v${v}')).FRAGMENTS;`).join('\n')}
    default:
      return null;
  }
}
`;
}

/** Writes version `version` under `root`, refusing to overwrite one that exists. */
export function writeVersion(root: string, version: number, fragments = makeFragments()): void {
  const dir = join(root, `v${version}`);
  if (existsSync(dir))
    throw new Error(`seal version ${version} already exists; versions are never rewritten`);
  mkdirSync(dir, { recursive: true });
  fragments.forEach((f, i) => writeFileSync(join(dir, `f${i}.ts`), fragmentModule(i, f)));
  writeFileSync(join(dir, 'index.ts'), versionIndex());
  const versions = readdirSync(root)
    .map((n) => /^v(\d+)$/.exec(n)?.[1])
    .filter((n): n is string => n !== undefined)
    .map(Number);
  writeFileSync(join(root, 'registry.ts'), registryModule(versions));
}

const here = dirname(fileURLToPath(import.meta.url));
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const i = process.argv.indexOf('--version');
  const version = Number(process.argv[i + 1]);
  if (i < 0 || !Number.isInteger(version) || version < 1 || version > 65535) {
    console.error('usage: tsx tools/gen-seal-material.ts --version <1..65535>');
    process.exit(2);
  }
  writeVersion(join(here, '..', 'src', 'save', 'seal'), version);
  console.log(`wrote seal version ${version}. Commit src/save/seal/.`);
}
